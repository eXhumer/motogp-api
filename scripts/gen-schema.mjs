#!/usr/bin/env node
// Builds src/schema.ts from the types the probe inferred (probe-out/shapes.d.ts).
//
//   npm run probe && npm run gen-schema [-- --in probe-out/shapes.d.ts --out src/schema.ts]
//
// Example values are stripped (they come from real riders and accounts). Only the endpoints listed
// in NAMES are emitted; the rest are hand-written in src/type.ts.
import { readFile, writeFile } from 'node:fs/promises';

import { parseArgs } from './lib.mjs';

/** probe name -> exported type name */
const NAMES = {
  ResultsEvents: 'ResultsEvents',
  ResultsCategories: 'ResultsCategories',
  ResultsSessions: 'ResultsSessions',
  Classification: 'Classification',
  Standings: 'Standings',
  StandingsFiles: 'StandingsFiles',
  EntryList: 'EntryList',
  ChampionshipFiles: 'ChampionshipFiles',
  Events: 'EventList',
  Categories: 'CategoryList',
  Teams: 'Teams',
  BmwAward: 'BmwAward',
  WorldChampions: 'WorldChampions',
  WorldStandings: 'WorldStandings',
  LastSession: 'LastSession',
  PulseBypodiums: 'PulseRanking',
  StatisticsByworldChampions: 'WorldChampionsTable',
  CircuitRecords: 'CircuitRecords',
  RidersPlacement: 'RidersPlacement',
  RidersPoles: 'RidersPoles',
  RiderPhotos: 'RiderPhotos',
  RiderInfo: 'RiderInfo',
  RiderCareer: 'RiderCareer',
  RiderEventStats: 'RiderEventStats',
  RiderStatsSummary: 'RiderStatsSummary',
  RiderLegacyStatistics: 'RiderLegacyStatistics',
  RiderComparison: 'RiderComparison',
};

const args = parseArgs();
const source = await readFile(typeof args.in === 'string' ? args.in : 'probe-out/shapes.d.ts', 'utf8');
const blocks = new Map(
  source
    .split(/\n(?=export type )/)
    .map((block) => [/^export type (\w+)/.exec(block)?.[1], block])
    .filter(([name]) => name),
);

let out = `// Generated by scripts/gen-schema.mjs from real responses. Do not edit by hand: re-run the probe instead.\n// Fields absent from some samples are optional. Values the samples never showed are \`unknown\`.\n\n`;
const missing = [];
for (const [probe, name] of Object.entries(NAMES)) {
  const block = blocks.get(probe);
  if (!block) {
    missing.push(probe);
    continue;
  }
  out += `${block
    .replace(/\s*\/\/ e\.g\. .*$/gm, '')
    .replace(new RegExp(`^export type ${probe}\\b`), `export type ${name}`)
    .trim()}\n\n`;
}
await writeFile(typeof args.out === 'string' ? args.out : 'src/schema.ts', out.trimEnd() + '\n');
console.log(`Wrote ${Object.keys(NAMES).length - missing.length} types.${missing.length ? ` No sample for: ${missing.join(', ')}` : ''}`);
